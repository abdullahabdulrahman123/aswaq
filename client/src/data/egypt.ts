/** أسماء المحافظات بس — للقوايم */
export const GOVERNORATE_NAMES = GOVERNORATES.map((g) => g.name);

export function citiesOf(governorate: string): string[] {
  return GOVERNORATES.find((g) => g.name === governorate)?.cities ?? [];
}

/**
 * خدمات تحديد الموقع بترجّع الاسم بصيغتها هي ("محافظة القاهرة"، "Cairo
 * Governorate"). بنشيل الزوايد ونقارن بقايمتنا عشان نلاقي المحافظة الصح.
 * بيرجّع null لو ملقيناش — وساعتها بنسيب المستخدم يختار بنفسه.
 */
export function matchGovernorate(raw: string | null | undefined): string | null {
  if (!raw) return null;
  const cleaned = raw
    .replace(/محافظة/g, '')
    .replace(/governorate/gi, '')
    .replace(/[أإآ]/g, 'ا')
    .trim();
  if (!cleaned) return null;

  return (
    GOVERNORATE_NAMES.find((n) => n.replace(/[أإآ]/g, 'ا') === cleaned) ??
    GOVERNORATE_NAMES.find((n) => {
      const norm = n.replace(/[أإآ]/g, 'ا');
      return norm.includes(cleaned) || cleaned.includes(norm);
    }) ??
    null
  );
}
